import { App } from 'octokit';
import { env } from '@/lib/env';
import type { KitFile } from '@/lib/kit/build';

// One private repository per project, created through the studio's GitHub App installation.
// First build commits to main; later syncs go on a branch with a pull request so changes are reviewed.

async function octo() {
  const g = env.github();
  const app = new App({ appId: g.appId, privateKey: g.privateKey });
  return { kit: await app.getInstallationOctokit(g.installationId), org: g.org };
}

export async function ensureKitRepo(slug: string, client: string) {
  const { kit, org } = await octo();
  const name = `${slug}-brand-kit`;
  try {
    const { data } = await kit.rest.repos.get({ owner: org, repo: name });
    return data.full_name;
  } catch (e) {
    if ((e as { status?: number }).status !== 404) throw e;
  }
  const isOrg = await kit.rest.orgs.get({ org }).then(() => true).catch(() => false);
  const body = { name, private: true, auto_init: true, description: `${client} brand kit: assets, tokens, guidelines, templates. Maintained by Lost Property.` };
  const { data } = isOrg ? await kit.rest.repos.createInOrg({ org, ...body }) : await kit.rest.repos.createForAuthenticatedUser(body);
  return data.full_name;
}

/** Commits the kit. `prune` lists folders the build owns: files in them that the build no longer makes are deleted. */
export async function commitKit(fullName: string, files: KitFile[], message: string, opts: { asPullRequest?: boolean; prune?: string[] } = {}) {
  const { kit } = await octo();
  const [owner, repo] = fullName.split('/');
  const { data: r } = await kit.rest.repos.get({ owner, repo });
  const base = r.default_branch;
  const { data: ref } = await kit.rest.git.getRef({ owner, repo, ref: `heads/${base}` });
  const { data: baseCommit } = await kit.rest.git.getCommit({ owner, repo, commit_sha: ref.object.sha });

  const tree = await Promise.all(files.map(async (f) => {
    const isText = typeof f.content === 'string';
    const { data: blob } = await kit.rest.git.createBlob({ owner, repo, content: isText ? (f.content as string) : Buffer.from(f.content as Uint8Array).toString('base64'), encoding: isText ? 'utf-8' : 'base64' });
    return { path: f.path, mode: '100644' as const, type: 'blob' as const, sha: blob.sha };
  }));
  let removed = 0;
  if (opts.prune?.length) {
    const { data: all } = await kit.rest.git.getTree({ owner, repo, tree_sha: baseCommit.tree.sha, recursive: 'true' });
    const keep = new Set(files.map((f) => f.path));
    const gone = all.tree.filter((e) => e.type === 'blob' && e.path && opts.prune!.some((d) => e.path!.startsWith(d)) && !keep.has(e.path));
    removed = gone.length;
    for (const g of gone) tree.push({ path: g.path!, mode: '100644' as const, type: 'blob' as const, sha: null as unknown as string });
  }
  const { data: newTree } = await kit.rest.git.createTree({ owner, repo, base_tree: baseCommit.tree.sha, tree });
  const { data: commit } = await kit.rest.git.createCommit({ owner, repo, message, tree: newTree.sha, parents: [ref.object.sha] });

  if (!opts.asPullRequest) {
    await kit.rest.git.updateRef({ owner, repo, ref: `heads/${base}`, sha: commit.sha });
    return { commit: commit.sha, pr: null as string | null, removed };
  }
  const branch = `sync/${new Date().toISOString().slice(0, 16).replace(/[:T]/g, '-')}`;
  await kit.rest.git.createRef({ owner, repo, ref: `refs/heads/${branch}`, sha: commit.sha });
  const { data: pr } = await kit.rest.pulls.create({ owner, repo, head: branch, base, title: message, body: 'Generated by the Lost Property brand platform after a Figma sync. Review the changes, then merge to publish them to the kit.' });
  return { commit: commit.sha, pr: pr.html_url, removed };
}

/** Deletes a kit repository. Only used when the studio explicitly ticks "also delete the repository". */
export async function deleteKitRepo(fullName: string) {
  const { kit } = await octo();
  const [owner, repo] = fullName.split('/');
  try { await kit.rest.repos.delete({ owner, repo }); return true; }
  catch (e) { if ((e as { status?: number }).status === 404) return true; throw e; }
}
