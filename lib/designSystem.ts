// A design system for AI: one folder that tells Claude (or any AI tool) how to build interfaces, documents and
// layouts in the brand. DESIGN.md is the spec; brand.css turns it into working styles; preview.html shows it;
// tokens, logos and fonts come from the kit. It uploads to Claude as a skill.

const kebab = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'brand';
const sat = (hex: string) => { const n = parseInt(hex.slice(1), 16); const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => v / 255); return Math.max(...c) - Math.min(...c); };

/** Picks working roles from the palette: background, text, accent and a quiet surface. */
export function roles(colours: { name: string; hex: string; role?: string }[]) {
  const by = (re: RegExp) => colours.find((c) => re.test(`${c.name} ${c.role || ''}`));
  const sorted = [...colours].sort((a, b) => lum(b.hex) - lum(a.hex));
  const paper = by(/background|paper|base|white|cream|light/i) || sorted[0] || { name: 'White', hex: '#FFFFFF' };
  const ink = by(/text|ink|black|dark|charcoal/i) || sorted[sorted.length - 1] || { name: 'Black', hex: '#000000' };
  const accent = by(/primary|accent|signature|lead|core/i) || [...colours].filter((c) => c !== paper && c !== ink).sort((a, b) => sat(b.hex) - sat(a.hex))[0] || ink;
  const surface = sorted.find((c) => c !== paper && lum(c.hex) > 0.75) || paper;
  return { paper, ink, accent, surface, onAccent: lum(accent.hex) > 0.6 ? ink : paper };
}

export function designSystemFiles(snap: Snapshot, fonts: ProjectFont[], files: string[], aiDonts?: string[]) {
  const client = snap.client, base = kebab(client);
  const name = `${base}-design-system`;
  const r = roles(snap.colours);
  const display = fonts.find((f) => f.role === 'display' && f.name) || fonts.find((f) => f.name);
  const body = fonts.find((f) => f.role === 'body' && f.name) || display;
  const caption = fonts.find((f) => f.role === 'caption' && f.name) || body;
  const fontFiles = files.filter((f) => f.startsWith('assets/fonts/') && /\.(woff2?|otf|ttf)$/i.test(f));
  const logos = files.filter((f) => /^assets\/logo\/.+\.(svg|png)$/i.test(f));
  const tokens = files.filter((f) => f.startsWith('tokens/'));
  const chapters = snap.guide?.chapters || [];
  const fam = (f?: ProjectFont) => (f ? `'${f.name}', ${f.role === 'caption' ? 'ui-monospace, ' : ''}system-ui, sans-serif` : 'system-ui, sans-serif');
  const v = (c: { name: string }) => `--color-${kebab(c.name)}`;

  const css = `/* ${client} design system: brand.css. Generated by Lost Property. Use these variables and classes; don't add colours or fonts. */
${fontFiles.map((f) => { const fam2 = fonts.find((x) => f.toLowerCase().includes(kebab(x.name)))?.name || f.split('/')[2]; return `@font-face { font-family: '${fam2}'; src: url('${f}'); font-display: swap; }`; }).join('\n')}
:root {
${snap.colours.map((c) => `  ${v(c)}: ${c.hex};`).join('\n')}
  --paper: var(${v(r.paper)}, ${r.paper.hex});
  --ink: var(${v(r.ink)}, ${r.ink.hex});
  --accent: var(${v(r.accent)}, ${r.accent.hex});
  --on-accent: ${r.onAccent.hex};
  --surface: ${r.surface.hex};
  --font-display: ${fam(display)};
  --font-body: ${fam(body)};
  --font-caption: ${fam(caption)};
  --space-1: 4px; --space-2: 8px; --space-3: 16px; --space-4: 24px; --space-5: 40px; --space-6: 64px;
  --radius: 4px;
}
body { margin: 0; background: var(--paper); color: var(--ink); font: 16px/1.5 var(--font-body); }
h1, h2, h3, .display { font-family: var(--font-display); font-weight: 400; line-height: 1.1; margin: 0 0 var(--space-3); }
h1 { font-size: clamp(36px, 6vw, 72px); } h2 { font-size: clamp(26px, 3.5vw, 40px); } h3 { font-size: 22px; }
.eyebrow, .caption { font-family: var(--font-caption); font-size: 12px; letter-spacing: .06em; text-transform: uppercase; }
.btn { display: inline-flex; align-items: center; gap: 8px; height: 44px; padding: 0 20px; border-radius: var(--radius); border: 1px solid var(--ink); background: transparent; color: var(--ink); font: 500 15px var(--font-body); cursor: pointer; text-decoration: none; }
.btn.primary { background: var(--accent); border-color: var(--accent); color: var(--on-accent); }
.card { background: var(--surface); border-radius: var(--radius); padding: var(--space-4); }
.section { padding: var(--space-6) var(--space-4); }
`;

  const md = `# ${client} design system

${snap.line}

This is the ${client} brand as a design system, for building interfaces, documents, decks and layouts. It's generated from the ${client} guidelines by Lost Property. When anything here disagrees with the guidelines, the guidelines win.

## How to use it
1. Use \`brand.css\`: its variables and classes are the system. Don't add colours, fonts, shadows or effects it doesn't define.
2. Start layouts from the roles below. One accent moment per screen or page is usually enough.
3. Use the logo files in \`assets/logo/\` as supplied (see "Rules for AI").
4. Open \`preview.html\` to see the system working.

## Colour
| Token | Name | HEX | Use |
| --- | --- | --- | --- |
${snap.colours.map((c) => `| \`${v(c)}\` | ${c.name} | ${c.hex} | ${c.role || ''} |`).join('\n')}

Working roles:
- Background (\`--paper\`): ${r.paper.name} ${r.paper.hex}
- Text (\`--ink\`): ${r.ink.name} ${r.ink.hex}
- Accent (\`--accent\`): ${r.accent.name} ${r.accent.hex}, with text in ${r.onAccent.hex}
- Surface (\`--surface\`): ${r.surface.hex}, for cards and panels

## Typography
${fonts.filter((f) => f.name).map((f) => `- **${f.label || f.role}** (\`--font-${f.role === 'display' ? 'display' : f.role === 'caption' ? 'caption' : 'body'}\`): ${f.name}${f.files.some((x) => x.licence === 'licensed') ? '' : '. Not included: install it, or use the system fallback and say so'}`).join('\n') || '- Not set yet.'}

Scale: display clamp(36px, 6vw, 72px) · heading clamp(26px, 3.5vw, 40px) · subheading 22px · body 16px / 1.5 · caption 12px uppercase, tracked +6%.

## Space and shape
Spacing steps 4, 8, 16, 24, 40, 64 px (\`--space-1\` to \`--space-6\`). Corner radius 4px. No drop shadows or gradients unless the guidelines show them.

## Components
- **Button:** \`.btn\` outlined in ink; \`.btn.primary\` filled with the accent. 44px high. Sentence-case labels.
- **Card:** \`.card\` on the surface colour, 24px padding.
- **Section:** \`.section\`, 64px vertical rhythm.
- **Eyebrow / caption:** \`.eyebrow\` in the caption face above headlines.

## Files
${[...logos.map((f) => `- \`${f}\``), ...tokens.map((f) => `- \`${f}\``), ...fontFiles.map((f) => `- \`${f}\``)].join('\n') || '- None yet.'}

## The guidelines
${chapters.map((c) => { const t = chapterText(c).filter((x) => x.length > 2).map((x) => x.replace(/\n+/g, ' ')).join(' ').slice(0, 1800); const rules = c.rules.map((x) => `- ${x.title}: ${x.text}`).join('\n'); return `### ${c.title}\n${rules ? rules + '\n' : ''}${t}`; }).join('\n\n')}

${aiRulesMd({ client, files, watchouts: watchoutsFrom(chapters.flatMap(chapterText)), donts: aiDonts })}
`;

  const skill = `---
name: ${name}
description: The ${client} design system. Use whenever building a ${client} interface, web page, app screen, document, deck or layout, to get its colours, type, spacing, components and logo rules exactly right.
---

# ${client} design system

Read \`DESIGN.md\` first; it is the spec. Build with \`brand.css\` (link it, or copy its variables), and use the files in \`assets/\` and \`tokens/\` as supplied.

- Use only the colours, fonts, spacing and components defined. Never invent new ones.
- Follow "Rules for AI" in DESIGN.md exactly; it's stricter than the guide on purpose.
- When you finish, list the tokens, components and logo file you used.
`;

  const preview = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${client} design system</title><link rel="stylesheet" href="brand.css">
<style>.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(160px,1fr));gap:var(--space-3)}.sw{border-radius:var(--radius);overflow:hidden;border:1px solid rgba(0,0,0,.08)}.sw div{height:96px}.sw p{margin:0;padding:8px 10px;font-size:13px}.logo{background:var(--surface);padding:var(--space-4);border-radius:var(--radius);display:flex;align-items:center;justify-content:center;height:120px}.logo img{max-width:80%;max-height:70px}</style></head>
<body><main class="section" style="max-width:1080px;margin:0 auto">
<p class="eyebrow">Design system</p><h1>${client}</h1><p>${snap.line}</p>
<h2 style="margin-top:var(--space-6)">Colour</h2><div class="grid">${snap.colours.map((c) => `<div class="sw"><div style="background:${c.hex}"></div><p>${c.name}<br><span class="caption">${c.hex}</span></p></div>`).join('')}</div>
<h2 style="margin-top:var(--space-6)">Type</h2><p class="display" style="font-size:56px">Display ${display?.name || ''}</p><h2>Heading in the display face</h2><p>Body copy in ${body?.name || 'the body face'}. The quick brown fox jumps over the lazy dog.</p><p class="caption">Caption · ${caption?.name || ''}</p>
<h2 style="margin-top:var(--space-6)">Components</h2><p><a class="btn primary" href="#">Primary action</a> <a class="btn" href="#">Secondary</a></p><div class="card" style="max-width:360px"><p class="eyebrow">Card</p><h3>A card on the surface colour</h3><p>Short supporting copy.</p></div>
${logos.length ? `<h2 style="margin-top:var(--space-6)">Logo</h2><div class="grid">${logos.filter((l) => l.endsWith('.svg')).slice(0, 6).map((l) => `<div class="logo"><img src="${l}" alt=""></div>`).join('')}</div>` : ''}
</main></body></html>`;

  return { folder: name, files: { 'SKILL.md': skill, 'DESIGN.md': md, 'brand.css': css, 'preview.html': preview }, include: [...logos, ...tokens, ...fontFiles], roles: r };
}
